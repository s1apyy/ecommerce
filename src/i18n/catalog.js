export function translateCategory(slug, locale = 'en', fallback = '') {
  const entry = CATEGORIES[slug]
  if (entry?.[locale]) return entry[locale]
  if (entry?.en) return entry.en
  if (fallback) return fallback
  return String(slug || '').replaceAll('-', ' ')
}

export function translateProductTitle(product, locale = 'en') {
  if (!product) return ''
  const entry = PRODUCT_TITLES[product.id]
  if (entry?.[locale]) return entry[locale]
  return product.title || entry?.en || ''
}
